#!/usr/bin/env python3
"""Regenerates packaging/icons/msfs-linuxrebind-<size>.png and src/ui/AppIcon.hpp.

packaging/icons/msfs-linuxrebind.svg is the master; this mirrors its shapes with Pillow so no SVG
rasterizer is needed on the build machine. Run from the repository root.
"""
import pathlib

from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORANGE, LIGHT, NAVY = "#ff9f1c", "#e8edf5", "#1b2740"


def render(size, supersample=4):
    s = lambda v: v * supersample  # noqa: E731
    W = 256 * supersample
    im = Image.new("RGBA", (W, W), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle([s(8), s(8), s(248), s(248)], radius=s(56), fill=NAVY)      # tile
    d.rounded_rectangle([s(112), s(104), s(144), s(216)], radius=s(16), fill=LIGHT)  # lever
    d.ellipse([s(88), s(44), s(168), s(124)], fill=ORANGE)                           # knob
    return im.resize((size, size), Image.LANCZOS)


def main():
    icons = ROOT / "packaging" / "icons"
    icons.mkdir(parents=True, exist_ok=True)
    for sz in (16, 32, 48, 64, 128, 256, 512):
        render(sz).save(icons / f"msfs-linuxrebind-{sz}.png")
    data = render(64).tobytes()
    with open(ROOT / "src" / "ui" / "AppIcon.hpp", "w") as f:
        f.write("#pragma once\n// Generated by packaging/make_icons.py from packaging/icons/msfs-linuxrebind.svg. 64x64 RGBA.\n"
                "#include <cstdint>\nnamespace lr::ui {\nconstexpr int kAppIconSize = 64;\n"
                "constexpr unsigned char kAppIconRgba[64 * 64 * 4] = {\n")
        for i in range(0, len(data), 32):
            f.write("    " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
        f.write("};\n}  // namespace lr::ui\n")
    print("icons and src/ui/AppIcon.hpp regenerated")


if __name__ == "__main__":
    main()
